// 코드펜스에서 꺼낸 글을 MDX 본문에 넣기 전 활성 문법을 막는다.
//
// 펜스 안에서는 글자였던 것이 밖으로 나오면 문법이 된다. 실제로 두 번 빌드를
// 깨뜨렸다:
//   `Y_{t−1}`  → {…} 가 JSX 표현식으로 파싱되고 − 가 유효한 JS 문자가 아니다
//   `<18.5`    → < 가 태그 시작으로 읽히고 1 은 태그 이름이 될 수 없다
// 둘 다 빌드가 통째로 멈추므로 조용히 넘어가지는 않지만, 막는 곳이 여러 스크립트에
// 흩어져 있으면 새 변환기를 쓸 때마다 다시 밟는다. 그래서 한 곳에 둔다.
//
// `$$…$$` 안은 remark-math 가 먼저 토큰화하므로 이 함수를 쓰지 않는다.
export function escapeMdx(s) {
  return s
    .replace(/([{}])/g, '\\$1')
    // 공백이 뒤따르는 `<` 는 비교 연산자로 읽혀 안전하다. 붙어 있는 것만 막는다.
    .replace(/<(?=\S)/g, '\\<');
}
